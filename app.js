const $ = (s, r = document) => r.querySelector(s);
const $$ = (s, r = document) => [...r.querySelectorAll(s)];

function t(key) {
    return (I18N[lang] && I18N[lang][key]) || I18N.ru[key] || key
}

function renderProducts() {
    const grid = $("#productGrid");
    const filtered = products.filter(p => (activeFilter === "all" || p.category === activeFilter) && ((p.name[lang] || p.name.ru).toLowerCase().includes(searchTerm.toLowerCase()) || (p.type[lang] || p.type.ru).toLowerCase().includes(searchTerm.toLowerCase())));
    if (!filtered.length) {
        grid.innerHTML = `<div class="empty-state"><strong>${t("noResults")}</strong></div>`;
        return
    }
    grid.innerHTML = filtered.map((p, i) => `<article class="product-card" style="animation-delay:${Math.min(i*55,220)}ms">
 <div class="product-image"><img src="${p.image}" alt="${escapeHtml(p.name[lang]||p.name.ru)}" loading="lazy" onerror="this.onerror=null;this.src='https://images.unsplash.com/photo-1519238263530-99bdd11df2ea?auto=format&fit=crop&w=760&q=80'"><span class="product-badge">${escapeHtml(p.tag[lang]||p.tag.ru)}</span><button class="product-quick" data-product="${p.id}">${t("quickView")} <span>↗</span></button></div>
 <div class="product-meta"><div><h3 class="product-name">${escapeHtml(p.name[lang]||p.name.ru)}</h3><div class="product-category">${escapeHtml(p.type[lang]||p.type.ru)}</div></div><div class="product-price ${p.price?'':'muted'}">${p.price?escapeHtml(p.price):t("fromPrice")}</div></div>
 <div class="product-sizes"><span class="size-pill">${escapeHtml(p.sizes)}</span></div></article>`).join("");
}

function escapeHtml(s) {
    return String(s).replace(/[&<>"']/g, c => ({
        "&": "&amp;",
        "<": "&lt;",
        ">": "&gt;",
        '"': "&quot;",
        "'": "&#39;"
    } [c]))
}

function setLanguage(next) {
    lang = next;
    document.documentElement.lang = next;
    $$("[data-i18n]").forEach(el => {
        const val = t(el.dataset.i18n);
        if (val) el.innerHTML = val
    });
    $$("[data-i18n-placeholder]").forEach(el => el.placeholder = t(el.dataset.i18nPlaceholder));
    $$("[data-lang]").forEach(b => b.classList.toggle("active", b.dataset.lang === next));
    const menu = $(".menu-toggle");
    menu.setAttribute("aria-label", next === "ru" ? "Открыть меню" : "Menyuni ochish");
    renderProducts();
}

function showToast(message) {
    const el = $("#toast");
    el.textContent = message;
    el.classList.add("show");
    clearTimeout(toastTimer);
    toastTimer = setTimeout(() => el.classList.remove("show"), 2600)
}

function openProduct(id) {
    const p = products.find(x => x.id === id);
    if (!p) return;
    const dialog = $("#productDialog");
    $("#dialogContent").innerHTML = `<div class="dialog-product"><img src="${p.image}" alt="${escapeHtml(p.name[lang]||p.name.ru)}"><div class="dialog-product-copy"><p class="eyebrow"><span class="eyebrow-dot"></span>${escapeHtml(p.type[lang]||p.type.ru)}</p><h3>${escapeHtml(p.name[lang]||p.name.ru)}</h3><p>${escapeHtml(p.desc[lang]||p.desc.ru)}</p><p><strong>${escapeHtml(p.price||t("fromPrice"))}</strong><br>${escapeHtml(p.sizes)}</p><p>${t("productPriceNote")}</p><a class="button button-green" href="https://t.me/lumakids_uz" target="_blank" rel="noopener noreferrer">${t("productAsk")} <span>↗</span></a></div></div>`;
    if (typeof dialog.showModal === "function") dialog.showModal();
    else dialog.setAttribute("open", "");
}

function makeRequest(form) {
    const data = new FormData(form);
    const name = (data.get("name") || "").toString().trim(),
        contact = (data.get("contact") || "").toString().trim();
    if (!name || !contact) return null;
    const lines = [t("requestWholesale"), "", `${t("labelName")}: ${name}`, `${t("labelContact")}: ${contact}`, `${t("labelType")}: ${data.get("type")}`, `${t("labelVolume")}: ${data.get("volume")}`];
    const msg = (data.get("message") || "").toString().trim();
    if (msg) lines.push(`${t("labelMessage")}: ${msg}`);
    return lines.join("\n");
}

function attachForm() {
    const form = $("#wholesaleForm"),
        result = $("#wholesaleResult");
    form.addEventListener("submit", async e => {
        e.preventDefault();
        const request = makeRequest(form);
        if (!request) return;
        result.hidden = false;
        result.innerHTML = `<div>${t("formSuccess")}</div><textarea id="requestText" rows="6" readonly aria-label="Текст заявки">${request.replace(/</g,"&lt;")}</textarea><button type="button" id="copyRequest">${t("copyRequest")}</button>`;
        $("#copyRequest").addEventListener("click", async () => {
            try {
                await navigator.clipboard.writeText(request);
                showToast(t("copied"))
            } catch {
                const ta = $("#requestText");
                ta.focus();
                ta.select();
                showToast(t("copyFailed"))
            }
        });
    });
}
